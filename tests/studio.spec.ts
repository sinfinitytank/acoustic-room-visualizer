test('gizmo movement keeps listeners seated and custom measurements work', async ({ page }) => {
  await page.goto('/')
  await place(page, 'Sofa')
  const before = await data(page), sofa = before.design.objects.find((o: { kind: string }) => o.kind === 'sofa')
  const rect = (await page.locator('canvas').boundingBox())!
  const { PerspectiveCamera, Vector3 } = await import('three')
  const r = before.design.room, span = r.length * 1.65
  const camera = new PerspectiveCamera(42, rect.width / rect.height, 0.05, 200)
  camera.position.set(r.width / 2 + span * 0.8, r.height / 2 + span * 0.65, r.length / 2 + span)
  camera.lookAt(r.width / 2, r.height / 2, r.length / 2); camera.updateMatrixWorld()
  const project = (x: number, y: number, z: number) => { const p = new Vector3(x, y, z).project(camera); return { x: rect.x + (p.x + 1) * rect.width / 2, y: rect.y + (1 - p.y) * rect.height / 2 } }
  const handle = project(sofa.position[0] + 0.6, sofa.position[1], sofa.position[2])
  await page.mouse.move(handle.x, handle.y); await page.mouse.down(); await page.mouse.move(handle.x + 65, handle.y + 20, { steps: 12 }); await page.mouse.up()
  const moved = await data(page), afterSofa = moved.design.objects.find((o: { kind: string }) => o.kind === 'sofa')
  expect(afterSofa.position).not.toEqual(sofa.position)
  const listener = moved.design.objects.find((o: { kind: string }) => o.kind === 'listener')
  expect(listener.position[0]).toBeCloseTo(afterSofa.position[0] - sofa.size[0] * 0.22)
  await tab(page, 'Measure')
  await page.getByRole('button', { name: '＋ Measure two points' }).click()
  const a = project(0.2, 1.8, 0), b = project(3.5, 1.8, 0)
  await page.mouse.click(a.x, a.y); await page.mouse.click(b.x, b.y)
  await expect(page.getByText('Measurement 1', { exact: true })).toBeVisible()
})
