import { test, expect } from '@playwright/test'
const KEY = 'acoustic-room-workspace-v2'
const tab = async (page: import('@playwright/test').Page, name: string) => page.getByRole('button', { name, exact: true }).click()
const place = async (page: import('@playwright/test').Page, name: string) => { await tab(page, 'Library'); await page.getByRole('button', { name: `Place ${name}`, exact: true }).click() }
const data = async (page: import('@playwright/test').Page) => page.evaluate(key => JSON.parse(localStorage.getItem(key) || '{}'), KEY)

