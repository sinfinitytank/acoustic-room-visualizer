import {chromium,expect} from '@playwright/test';
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1280,height:900}});
await page.goto('http://127.0.0.1:5173');
await page.getByRole('button',{name:'Create a new room',exact:true}).click();
await page.getByRole('button',{name:'Files',exact:true}).click();
await page.getByRole('button',{name:'Open demo room',exact:true}).click();
await expect(page.getByLabel('Design name')).toHaveValue('The listening room');
await page.getByRole('button',{name:'Rays',exact:true}).click();
const cards=page.locator('.treatment-ray-card');
await expect(cards).toHaveCount(7);
await page.getByRole('button',{name:'All off',exact:true}).click();
await expect(page.locator('.treatment-ray-card[aria-pressed=true]')).toHaveCount(0);
await page.getByRole('button',{name:'Reflect from Absorber 1',exact:true}).click();
await expect(page.locator('.treatment-ray-card[aria-pressed=true]')).toHaveCount(1);
await page.getByRole('button',{name:'All on',exact:true}).click();
await expect(page.locator('.treatment-ray-card[aria-pressed=true]')).toHaveCount(7);
await cards.last().scrollIntoViewIfNeeded();
await page.screenshot({path:'/tmp/acoustic-treatment-controls.png'});
await browser.close();console.log('PASS: seven separate treatment buttons, individual toggle, all off and all on.');
