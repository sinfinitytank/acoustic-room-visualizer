import { chromium } from '@playwright/test';
const browser=await chromium.launch({headless:true,args:['--use-gl=angle','--use-angle=swiftshader']});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
await page.goto('http://127.0.0.1:5173');
await page.getByRole('button',{name:'Create a new room',exact:true}).click();
await page.getByRole('button',{name:'Files',exact:true}).click();
await page.getByRole('button',{name:'Open demo room',exact:true}).click();
await page.waitForFunction(()=>document.querySelector('input[aria-label="Design name"]')?.value==='The listening room');
await page.reload();
await page.getByRole('button',{name:'Library',exact:true}).click();
await page.getByRole('button',{name:'Edit Absorption panel',exact:true}).click();
await page.getByRole('button',{name:'2″',exact:true}).click();
if(await page.getByLabel('Custom thickness',{exact:true}).count())throw Error('Preset input is not locked');
await page.getByRole('button',{name:'Custom',exact:true}).click();
if(await page.getByLabel('Custom thickness',{exact:true}).inputValue()!=='4')throw Error('Custom not initialized to 4');
await page.getByRole('button',{name:'Rays',exact:true}).click();
await page.getByRole('button',{name:'Reset ray controls',exact:true}).click();
await page.waitForFunction(()=>JSON.parse(localStorage.getItem('acoustic-room-workspace-v2')).design.objects.every(o=>!o.reflect));
await page.evaluate(()=>{localStorage.clear();sessionStorage.clear()});
await page.reload();
await page.getByRole('button',{name:'Create a new room',exact:true}).click();
await page.getByRole('button',{name:'Files',exact:true}).click();
await page.getByRole('button',{name:'Open demo room',exact:true}).click();
await page.waitForFunction(()=>document.querySelector('input[aria-label="Design name"]')?.value==='The listening room');
await page.getByRole('button',{name:'Rays',exact:true}).click();
await page.screenshot({path:'/tmp/acoustic-refined.png'});
console.log('PASS: demo loads fresh and after refresh; presets lock; Custom starts at 4 inches; reset yields zero rays; demo loads after isolated storage clear.');
await browser.close();
